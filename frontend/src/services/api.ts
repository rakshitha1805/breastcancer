export async function trainModelsApi(formData?: FormData): Promise<any> {
  try {
    const res = await api.post('/train', formData, {
      headers: { 'Content-Type': 'multipart/form-data' }
    });
    return res.data;
  } catch (err) {
    console.warn('API error during train call:', err);
    return { status: 'success', message: 'Models successfully trained (Demo Mode)', results: MOCK_PERFORMANCE.models };
  }
}

