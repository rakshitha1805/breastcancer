export async function deleteHistoryItemApi(id: string): Promise<boolean> {
  try {
    await api.delete(`/history/${id}`);
    return true;
  } catch (err) {
    return true;
  }
}

export async function clearHistoryApi(): Promise<boolean> {
  try {
    await api.post('/history/clear');
    return true;
  } catch (err) {
    return true;
  }
}

export function getExportHistoryUrl(format: 'csv' | 'json' = 'csv'): string {
  return `${API_BASE_URL}/history/export?format=${format}`;
}
