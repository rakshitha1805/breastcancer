export async function predictSampleApi(features: Record<string, number>): Promise<PredictionResult> {
  try {
    const res = await api.post('/predict', { features });
    return res.data;
  } catch (err) {
    console.warn('API error, returning mock prediction:', err);
    // Simulate local prediction for offline dev
    const r = features['mean radius'] || 14;
    const isMalignant = r > 16.5 || (features['mean concave points'] || 0) > 0.08;
    return {
      ...MOCK_PREDICTION,
      prediction: isMalignant ? 'Malignant' : 'Benign',
      is_malignant: isMalignant,
      confidence: isMalignant ? 96.8 : 94.2,
      probabilities: isMalignant ? { Benign: 3.2, Malignant: 96.8 } : { Benign: 94.2, Malignant: 5.8 }
    };
  }
}

